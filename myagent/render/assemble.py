from __future__ import annotations

import re

from myagent import __version__
from myagent.render import render_section
from myagent.render.narrative import offline_narrative
from myagent.types import Role

_MARKER = re.compile(r"===[ \t]*SECTION:[ \t]*([A-Za-z0-9_]+)[ \t]*===", re.IGNORECASE)


def parse_markers(text: str) -> dict[str, str]:
    matches = list(_MARKER.finditer(text))
    out: dict[str, str] = {}
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        out[m.group(1).lower()] = text[m.end():end].strip()
    return out


def assemble_doc(role: Role, facts: dict, narratives: dict[str, str], mode: str,
                 facts_hash: str, sources: list[str], review_notes: str | None = None) -> str:
    parts = [
        f"<!-- generated by myagent v{__version__} | mode: {mode} | facts: {facts_hash[:12]} -->",
        f"# {role.title}",
        "",
    ]
    for sec in role.sections:
        parts.append(f"## {sec.title}")
        parts.append("")
        if sec.kind == "facts":
            parts.append(render_section(sec, facts, role))
        else:
            parts.append(narratives.get(sec.id) or offline_narrative(sec, facts, role))
        parts.append("")
    if review_notes:
        parts += ["## Review notes", "", review_notes, ""]
    parts += ["---", "", "## Sources", ""]
    parts += [f"- `{s}`" for s in sources] if sources else ["- (no source files recorded)"]
    return "\n".join(parts).rstrip() + "\n"