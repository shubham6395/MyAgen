def test_doc_index_links_other_docs():
    f = facts.new_facts()
    md = RENDERERS["doc_index"](f, roles.get_role("README"))
    assert "[PRD.md](PRD.md)" in md
    assert "[BLUEPRINT.md](BLUEPRINT.md)" in md
    assert "[README.md](README.md)" not in md


def test_offline_narrative_has_guidance_and_evidence(fixture_repo):
    f = analyze_repo(fixture_repo("fastapi_app"))
    role = roles.get_role("API")
    sec = next(s for s in role.sections if s.kind == "narrative")
    md = offline_narrative(sec, f, role)
