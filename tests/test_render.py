from myagent import facts, roles
from myagent.analyzer import analyze_repo
from myagent.render import RENDERERS
from myagent.render.assemble import assemble_doc, parse_markers
from myagent.render.narrative import SENTINEL, offline_narrative


def test_offline_api_doc(fixture_repo):
    f = analyze_repo(fixture_repo("fastapi_app"))
    role = roles.get_role("API")
    narratives = {
        s.id: offline_narrative(s, f, role)
        for s in role.sections if s.kind == "narrative"
    }
    md = assemble_doc(role, f, narratives, "offline", facts.facts_sha256(f), ["main.py"])
    for r in f["routes"]:
        assert f"| {r['method']} | `{r['path']}`" in md
    assert "## Sources" in md
    assert "generated by myagent" in md
    assert SENTINEL in md


def test_facts_sections_match_renderer(fixture_repo):
    f = analyze_repo(fixture_repo("fastapi_app"))
    role = roles.get_role("API")
    md = assemble_doc(role, f, {}, "offline", "abc123", [])
    for s in role.sections:
        if s.kind == "facts":
            assert RENDERERS[s.renderer](f, role) in md


def test_parse_markers_clean():
    text = "===SECTION: overview===\nHello\n===SECTION: auth===\nWorld"
    assert parse_markers(text) == {"overview": "Hello", "auth": "World"}


def test_parse_markers_messy():
    text = "preamble\n=== SECTION: Overview ===\nHello\n===SECTION:auth===\nWorld"
    m = parse_markers(text)
    assert m["overview"] == "Hello"
    assert m["auth"] == "World"


def test_parse_markers_none():
    assert parse_markers("no markers here") == {}


